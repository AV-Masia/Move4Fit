export function articleById(id: string): Article | undefined {
  return ARTICLES.find((a) => a.id === id);
}

/** Статья дня: сначала непрочитанные, по кругу в зависимости от дня. */
export function articleOfTheDay(readIds: string[] = [], today: Date = new Date()): Article {
  const unread = ARTICLES.filter((a) => !readIds.includes(a.id));
  const pool = unread.length > 0 ? unread : ARTICLES;
  const dayNumber = Math.floor(new Date(today.getFullYear(), today.getMonth(), today.getDate()).getTime() / (24 * 3600 * 1000));
  return pool[((dayNumber % pool.length) + pool.length) % pool.length];
}
