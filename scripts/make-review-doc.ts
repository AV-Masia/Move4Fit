/**
 * Собирает документ «На проверку специалисту» из кода приложения: `npm run review-doc`.
 * Документ не правится руками — он пересоздаётся, чтобы не расходиться с приложением.
 */
import { writeFileSync } from 'node:fs';

import { ARTICLES, CATEGORY_LABELS } from '../src/content/articles';
import { achievements } from '../src/domain/achievements';
import { EXERCISES, TRACKING_TESTS } from '../src/domain/exercises';
import { LEVEL_DESCRIPTIONS } from '../src/domain/functionalLevel';
import { GOAL_PRESETS, GOAL_RATINGS, GOAL_REVIEW_DAYS } from '../src/domain/goals';
import { BREAK_DAYS, BREAK_REASONS, PAIN_AREAS, PAIN_SIGNS } from '../src/domain/profile';
import { EASY_STREAK_TO_ADVANCE } from '../src/domain/progression';
import { CAPABILITY_LABELS } from '../src/domain/content';
import {
  CLEARANCE_FLAGS,
  FLAG_EXCLUSIONS,
  GMFCS_OPTIONS,
  MOTOR_ITEMS,
  RISK_LABELS as RISK,
  SAFETY_QUESTIONS,
} from '../src/domain/questionnaire';
import { TARGET_SESSIONS_PER_WEEK } from '../src/domain/selection';
import type { ExerciseRisk, FunctionalLevel } from '../src/domain/types';

const PART = { warmup: 'разминка', main: 'основная часть', cooldown: 'заминка' } as const;
const risks = (list: ExerciseRisk[]) => (list.length ? list.map((r) => RISK[r]).join(', ') : '—');
const levels = (list: FunctionalLevel[]) => list.map((l) => LEVEL_DESCRIPTIONS[l].title).join(', ');
const cell = (s: string) => s.replace(/\|/g, '/');

const out: string[] = [];
const p = (...lines: string[]) => out.push(...lines, '');

p(
  '# Move4Fit — на проверку специалисту',
  `Собрано автоматически из приложения ${new Date().toLocaleDateString('ru-RU')}. Всё ниже — черновик: его написал не врач.`,
  'Пожалуйста, отметьте по каждому пункту: **верно / исправить (как) / убрать**. Пустые места и вопросы в конце — то, чего в приложении ещё нет.',
);

p('## 1. Группы занятий (внутренний уровень; родитель видит название группы словами)');
out.push('| № | Название для родителя | Описание |', '|---|---|---|');
([1, 2, 3, 4, 5] as FunctionalLevel[]).forEach((l) =>
  out.push(`| ${l} | ${LEVEL_DESCRIPTIONS[l].title} | ${cell(LEVEL_DESCRIPTIONS[l].text)} |`),
);
p(
  '',
  'Правило: ходит сам → группа 1 (если ходит по улице, по лестнице без перил и бегает; до 4 лет — достаточно самостоятельной ходьбы), иначе 2. Ходит с ходунками или за руку → 3. Сидит сам или держит голову и сидит с поддержкой → 4. Иначе → 5.',
);

p(
  'Диагноз в приложении не спрашивается и не хранится. Если врач называл родителю уровень GMFCS, родитель может его указать (необязательно). Тогда для подбора берётся более осторожный уровень из двух: названный врачом или полученный по тесту. При расхождении на 2 ступени и больше родителя просят перепроверить ответы.',
  'Вопрос к вам: верно ли брать более осторожный уровень? Применима ли шкала GMFCS к детям без ДЦП, которые занимаются в приложении?',
  '',
  'Как уровни GMFCS подписаны для родителя:',
  ...GMFCS_OPTIONS.map((o) => `- ${o.label}`),
);

p('## 2. Тест движений из 5 пунктов');
p('Родитель выбирает в каждом пункте самое сложное, что ребёнок обычно делает сам. Состав пунктов и формулировки — черновик.');
MOTOR_ITEMS.forEach((item, i) => {
  const cond = item.askIf ? `задаётся, только если уже есть «${CAPABILITY_LABELS[item.askIf].toLowerCase()}»` : 'задаётся всегда';
  p(
    `**${i + 1}. ${item.title}** — «${item.text}» (${cond})`,
    ...item.options.map(
      (o) =>
        `- ${o.label} → ${o.grants.length ? o.grants.map((c) => CAPABILITY_LABELS[c].toLowerCase()).join(', ') : 'ничего'}${o.requires ? ` (вариант показывается, только если уже есть «${CAPABILITY_LABELS[o.requires].toLowerCase()}»)` : ''}`,
    ),
  );
});

p('## 3. Ограничения и противопоказания: вопросы и что они меняют');
out.push('| Вопрос | Какие упражнения исключаются | Нужно разрешение врача | Есть ответ «не знаю» |', '|---|---|---|---|');
SAFETY_QUESTIONS.forEach((q) =>
  out.push(
    `| ${cell(q.text)} | ${risks(FLAG_EXCLUSIONS[q.flag])} | ${CLEARANCE_FLAGS.includes(q.flag) ? 'да' : 'нет'} | ${q.allowUnknown ? 'да — исключаем, как при «да»' : 'нет'} |`,
  ),
);
p('');
p(
  'Раньше часть исключений ставилась автоматически по диагнозу (синдром Дауна — сгибание шеи и положение вниз головой; спинномозговая грыжа — прыжки). Диагноз больше не хранится, поэтому теперь это прямые вопросы о запрете врача с ответом «не знаю».',
  'Вопросы к вам: достаточно ли вопроса о запрете врача, чтобы заменить автоматическую осторожность по диагнозу? Нужно ли разрешение врача при ответе «да» на вопрос о шее? Каких запретов врача не хватает в списке (запрет на опору на ноги, корсет, ортезы)?',
);

p(`## 4. Упражнения (${EXERCISES.length})`);
EXERCISES.forEach((e) => {
  p(
    `### ${e.title}`,
    `${e.description}`,
    `- Часть занятия: ${PART[e.part]}. Группы: ${levels(e.levels)}. С возраста: ${e.minAge} лет.`,
    `- Риски: ${risks(e.risks)}.${e.equipment ? ` Понадобится: ${e.equipment.join(', ')}.` : ''}`,
    ...e.variants.map((v) => `- Сложность ${v.difficulty}: ${v.instructions}`),
  );
});

p('## 5. Занятие, неделя и прогрессия');
p(
  `- Занятие: 1 разминка + 3 основных + 1 заминка; сначала те упражнения, которые давно не делали.`,
  `- Цель недели: ${TARGET_SESSIONS_PER_WEEK} занятия, не чаще одного в день; после занятия на следующий день предлагается отдых. Сейчас одинаково для всех групп.`,
  `- «Легко» ${EASY_STREAK_TO_ADVANCE} раза подряд → упражнение на шаг сложнее. «Тяжело» → на шаг проще. Отзыв можно уточнить по отдельному упражнению.`,
  `- Пропущенное упражнение не влияет на сложность и предлагается в следующий раз.`,
  `- Все упражнения на максимуме и «легко» → предложение пройти анкету заново.`,
);

p('## 6. Безопасность');
p(
  '- Перед первым занятием родитель читает и принимает правила (текст — в приложении, экран «Правила занятий»).',
  '- Перед каждым занятием вопрос «Как ребёнок сегодня?»: бодрый / устал / что-то болит. При усталости — совет отдохнуть, при боли — занятие не проводится.',
  '- После отметки о боли: сложность всех упражнений занятия снижается, занятия на паузе, пока родитель не нажмёт «Ребёнку лучше».',
  `- Признаки боли, которые отмечает родитель: ${PAIN_SIGNS.map((s) => s.label.toLowerCase()).join('; ')}.`,
  `- Где болело: ${PAIN_AREAS.map((a) => a.label.toLowerCase()).join(', ')}.`,
  `- Перерыв больше ${BREAK_DAYS} дней: вопрос о причине (${BREAK_REASONS.map((r) => r.label.toLowerCase()).join(' / ')}). Болел или пауза → все упражнения на шаг проще; занимались со специалистом → без изменений.`,
  '- Новая особенность, требующая разрешения врача, при повторной анкете → разрешение спрашивается заново.',
);

p('## 7. Цели семьи');
p(`Родитель выбирает одну цель или пишет свою. Через ${GOAL_REVIEW_DAYS} дней — оценка: ${GOAL_RATINGS.map((r) => r.label.toLowerCase()).join(' / ')}. На подбор упражнений цель пока не влияет.`);
([1, 2, 3, 4, 5] as FunctionalLevel[]).forEach((l) =>
  out.push(`- **${LEVEL_DESCRIPTIONS[l].title}:** ${GOAL_PRESETS.filter((g) => g.levels.includes(l)).map((g) => g.title).join('; ')}`),
);
p('');

p('## 8. Тесты динамики');
out.push('| Тест | Как проводить | Единица | Группы |', '|---|---|---|---|');
TRACKING_TESTS.forEach((t) => out.push(`| ${t.title} | ${cell(t.instructions)} | ${t.unit} | ${levels(t.levels)} |`));
p('');

p('## 8а. Значки и шкала динамики');
p('Значки даются за регулярность и заботу, а не за результат ребёнка. После занятия с отметкой о боли новые значки не показываются.');
achievements({ sessions: [], trackingResults: [] }).forEach((a) => out.push(`- ${a.icon} **${a.title}** — ${a.how.toLowerCase()}`));
p(
  '',
  'Шкала динамики: по каждому тесту сравниваем первый и последний результат; изменение в пределах ±10 % считается «без изменений». При снижении родитель видит спокойное пояснение и совет показать сводку куратору или врачу.',
  'Вопрос к вам: не подталкивают ли значки заниматься через усталость или боль? Верна ли формула шкалы?',
);

p(`## 9. Статьи для родителей (${ARTICLES.length})`);
ARTICLES.forEach((a) => {
  p(`### ${a.title}`, `_${CATEGORY_LABELS[a.category]} · ${a.minutes} мин · ${a.reviewedBy ? `проверено: ${a.reviewedBy}` : 'не проверено'}_`);
  a.body.forEach((b) => p(b.startsWith('## ') ? `**${b.slice(3)}**` : b));
});

p(
  '## 10. Чего в приложении ещё нет — нужны ваши решения',
  '1. **Ежедневные «минутки»** на 2–3 минуты в дни отдыха, особенно для групп «Сидит» и «Нужна поддержка»: какие задания и для кого?',
  '2. **Норма занятий в неделю по группам:** сейчас 3 для всех. Какой она должна быть для каждой группы?',
  '3. **Стоп-сигналы кроме боли** (новая хромота, потеря навыка, участившиеся приступы): какие вопросы задавать родителю и как часто?',
  '4. **Упражнения под цели:** какие упражнения работают на каждую цель из раздела 7? Каких упражнений не хватает?',
  '5. **Малыши 1–2 лет, которые ходят сами:** для них сейчас подбирается одно упражнение. Что им предлагать?',
  '6. **Видео:** какие упражнения снимать в первую очередь?',
  '7. **Темы статей:** чего не хватает родителям в разделе «Читать»?',
  '8. **Выбор сложности родителем:** в карточке упражнения родитель может сам выбрать любой из трёх вариантов и отметить упражнение отдельно от занятия. При повышении показывается предупреждение. Допустимо ли это, или повышать сложность должно только приложение?',
);

writeFileSync('docs/na-proverku-specialistu.md', out.join('\n'), 'utf8');
console.log(`docs/na-proverku-specialistu.md: ${out.length} строк`);
